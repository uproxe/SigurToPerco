def sample_rows():
    """Строки «как в файле»: 3 служебные строки, заголовок, данные."""
    rows = [["Отчет Сотрудники"], ["Подразделения: все"], [], list(HEADER)]
    rows += [list(r) for r in ROWS]
    return rows


def write_sample_xlsx(path):
    from openpyxl import Workbook
    wb = Workbook()
    ws = wb.active
    ws.title = "Сотрудники"
    for r in sample_rows():
        ws.append(r)
    wb.save(path)
    return path


def write_sample_html_xls(path):
    """Некоторые системы сохраняют «xls», который на деле HTML-таблица."""
    out = ["<html><body><table>"]
    for r in sample_rows():
        cells = "".join("<td>%s</td>" % ("" if v is None else v) for v in r)
        out.append("<tr>%s</tr>" % cells)
    out.append("</table></body></html>")
    with open(path, "w", encoding="cp1251") as f:
        f.write("\n".join(out))
    return path
